SELECT CURRENT_DATE() AS TODAY;

CREATE DATABASE FINANCE_BOOTCAMP;

CREATE SCHEMA FINANCE_BOOTCAMP.RAW;

CREATE TABLE FINANCE_BOOTCAMP.RAW.TRANSACTIONS (
    TRANSACTION_ID NUMBER,
    CATEGORY VARCHAR(50),
    AMOUNT NUMBER(10,2),
    TRANSACTION_DATE DATE
);

